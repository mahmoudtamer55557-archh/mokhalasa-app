import os
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

def build_playbook():
    doc = Document()
    for s in doc.sections:
        s.top_margin = Inches(1)
        s.bottom_margin = Inches(1)
        s.left_margin = Inches(1)
        s.right_margin = Inches(1)

    def add_h(text, level=1, color=(11, 45, 74)):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        p.paragraph_format.bidi = True
        p.paragraph_format.space_before = Pt(14)
        p.paragraph_format.space_after = Pt(6)
        run = p.add_run(text)
        run.bold = True
        run.font.name = 'Arial'
        run.font.size = Pt(20 if level==1 else (15 if level==2 else 12.5))
        run.font.color.rgb = RGBColor(*color)
        return p

    def add_p(text, bold=False, color=(51, 65, 85), size=11, space_after=4):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        p.paragraph_format.bidi = True
        p.paragraph_format.space_after = Pt(space_after)
        run = p.add_run(text)
        run.bold = bold
        run.font.name = 'Arial'
        run.font.size = Pt(size)
        run.font.color.rgb = RGBColor(*color)
        return p

    # Header
    add_h("دليل التشغيل الواقعي والتنفيذ الميداني لمنصة مُخَلّصة (Mokhalasa)", level=1, color=(11, 45, 74))
    add_p("بدون مجاملة: كيف تحول الفكرة إلى شركة مليارية على أرض الواقع وقانونياً في مصر", bold=True, color=(16, 185, 129), size=12)
    add_p("إعداد وتوثيق: محمود تامر وأخته • 2026", bold=False, color=(100, 116, 139), size=10, space_after=16)

    # -------------------------------------------------------------
    # SECTION 1: THE ESCROW PUZZLE IN EGYPT
    # -------------------------------------------------------------
    add_h("المحور الأول: اللغز الأكبر.. كيف تنشئ حساب الضمان (Escrow) قانونياً في مصر؟", level=2, color=(11, 45, 74))
    add_p("⚠️ الصدمة القانونية التي لا يخبرك بها أحد:", bold=True, color=(220, 38, 38), size=11)
    add_p("إذا فتحت حساباً بنكياً شخصياً باسمك واستقبلت فيه أموال مشتري السيارات (400 أو 500 ألف جنيه) كـ 'أمانة' لحين سداد البنك، فأنت ترتكب جريمة جنائية يعاقب عليها القانون المصري بالحبس والغرامة بموجب:\n• قانون 146 لسنة 1988 (حظر تلقي الأموال لغير الشركات المقيدة / توظيف الأموال).\n• قانون مكافحة غسل الأموال رقم 80 لسنة 2002.\nالبنك سيجمد حسابك فوراً بمجرد تكرار هذه التحويلات وسيخطر وحدة غسل الأموال (AML).")

    add_p("💡 كيف تحل هذا اللغز بنسبة 100% قانونياً؟ (3 مراحل عملية):", bold=True, color=(16, 185, 129), size=11.5)
    phases = [
        ("المرحلة 1: في مرحلة الانطلاق والـ MVP (نظام الشيك المصرفي المباشر):",
         "• المنصة لا تستلم مليم كاش في حسابها الشخصي نهائياً!\n• المشتري يذهب إلى بنكه ويصدر 'شيك مصرفي مقبول الدفع' (Certified Cashier Check) صادر باسم البنك الدائن مباشرة (مثال: لصالح البنك التجاري الدولي CIB - سداد مديونية سيارة العميل فلان).\n• محامي المنصة يتوجه مع المشتري والبائع لإيداع الشيك في خزينة البنك الدائن واستلام إيصال السداد الرسمي المعتمد فوراً.\n• المنصة تتقاضى فقط عمولتها ورسوم الفحص عبر فاتورة رسمية مسجلة.\n• النتيجة: أمان قانوني مطلق، لا شبهة غسل أموال، والبنك الدائن يرى شيكاً مصرفياً فيصدر المخالصة سريعاً."),
        ("المرحلة 2: بعد تأسيس شركة الـ LLC (الحساب التجاري المشروط):",
         "• فتح حساب جاري تجاري لشركة وساطة في بنك يقدم خدمات الشركات (مثل CIB، بنك مصر، QNB، أو مصرف أبوظبي الإسلامي ADIB).\n• توقيع عقد فتح حساب مشروط باتفاقية تسوية ثلاثية (Collection & Settlement Sub-Account) مرتبط بعقد وساطة تجارية موثق بالشهر العقاري."),
        ("المرحلة 3: التوسع والحصول على ترخيص التكنولوجيا المالية:",
         "• التقدم للبيئة التشريعية التجريبية للبنك المركزي (CBE Regulatory Sandbox) للحصول على رخصة ميسر مدفوعات رقمية (Payment Facilitator / PayFac) أو وسيط تسويات رقمية معتمد.")
    ]
    for ph_t, ph_d in phases:
        add_p(ph_t, bold=True, color=(11, 45, 74), size=11)
        for line in ph_d.split("\n"):
            add_p(line, bold=False, color=(51, 65, 85), size=10.5)

    # -------------------------------------------------------------
    # SECTION 2: HOW TO REACH BANKS & FINANCE COMPANIES
    # -------------------------------------------------------------
    add_h("المحور الثاني: كيف تخترق البنوك وشركات التمويل وتجعلهم يتعاملون معك؟", level=2, color=(11, 45, 74))
    add_p("1. إياك والذهاب لفرع البنك العادي:", bold=True, color=(220, 38, 38), size=11)
    add_p("موظف الفرع وظيفته خدمة عملاء الأفراد ولن يفهم طبيعة عملك وسيرفضك فوراً. أنت تبحث عن إدارات محددة في المقرات الرئيسية فقط.")

    add_p("2. من هو الشخص الذي تبحث عنه في البنك بالضبط؟", bold=True, color=(11, 45, 74), size=11)
    add_p("• رئيس قطاع معالجة الأصول والديون المتعثرة (Head of Remedial Assets / Workout Department).\n• مدير إدارة تحصيل قروض التجزئة المصرفية (Retail Collection & Recovery).")

    add_p("3. الشركات الأسهل والأسرع 10 أضعاف من البنوك (ابدأ بهم أولاً):", bold=True, color=(16, 185, 129), size=11)
    add_p("• شركة كونتكت للتمويل الاستهلاكي (Contact Finance): أضخم محفظة تقسيط سيارات في مصر وإدارتهم مرنة وسريعة جداً.\n• شركة درايف (Drive - GB Corp غبور): متخصصة بالكامل في تمويل سيارات المستعمل والجديد.\n• شركة فاليو (Valu - U-Drive): أسرع شركة في التحول الرقمي والشراكات الريادية.\n• شركة أمان للتمويل (Aman): انتشار قوي في جميع المحافظات.")

    add_p("4. السكربت الاحترافي لمقابلة مديري التسويات بالبنوك:", bold=True, color=(217, 119, 6), size=11)
    add_p("\"يا فندم، البنك عندكم بيعاني من قروض سيارات متعثرة، وتكلفة سحب السيارة عبر المحكمة وتخزينها في جراجات الحجز وبيعها في مزاد علني بتكلف البنك من 15% إلى 25% من قيمة القرض وبتاخد من سنة لسنتين في المحاكم، والبنك المركزي بيضغط عليكم لتخفيض نسبة الديون غير المنتظمة (NPLs).\nمنصة (مُخَلّصة) بتجيب لحضرتك مشتري كاش جاد جاهز يسدد كامل أصل المديونية وغرامات السداد المعجل فوراً بدون ما تصرفوا مليم في المحاكم وبدون قضايا. إحنا بنقفل لكم مديونيات متعثرة وبنحولها لكاش فوري في خزانة البنك خلال 5 أيام عمل فقط.\"", bold=False, color=(15, 23, 42), size=10.5)

    # -------------------------------------------------------------
    # SECTION 3: THE 5 REAL-WORLD LANDMINES
    # -------------------------------------------------------------
    add_h("المحور الثالث: الألغام الـ 5 الحقيقية على أرض الواقع (وكيف تحلها):", level=2, color=(11, 45, 74))
    mines = [
        ("1. لغم تأخير خطاب المخالصة من البنك (من أسبوع لـ 3 أسابيع):",
         "الحل: تسليم المشتري إيصال السداد المالي المختوم بختم شعار البنك في نفس اللحظة + توقيع إيصال استلام أمانة مشروط بالشهر العقاري يثبت حيازة المشتري للسيارة لحين صدور أصل الخطاب، وتوضيح المدة مسبقاً في عقد المنصة."),
        ("2. لغم مخالفات المرور المتراكمة والأحكام الجنائية الغيابية على البائع:",
         "الحل الإلزامي: اشتراط استخراج شهادة براءة ذمة من نيابة المرور (شهادة المخالفات) + كشف استعلام أمني على رقم الشاسيه واللوحات قبل توقيع أي عقد أو استلام أي مليم، وخصم قيمة المخالفات من سعر السيارة فوراً."),
        ("3. لغم تراجع المشتري فجأة بعد بدء إجراءات البنك:",
         "الحل: تطبيق شرط 'مبلغ جدية حجز غير مسترد في حال النكول غير المبرر' (يعادل 2.5% إلى 5% من الصفقة) لتعويض البائع والمنصة عن المصروفات الإدارية."),
        ("4. لغم السيارات ذات النزاع الأسري أو الورثة غير المعلنين:",
         "الحل: حظر التعامل مع أي طرف إلا المالك المقيد بالرخصة والبطاقة القومية السارية وجهاً لوجه، مع مطابقة الهوية الرقمية لمنع بيع سيارات الورثة أو النزاعات الزوجية."),
        ("5. لغم إلغاء ومنع التوكيلات بالمرور في مصر:",
         "الحل: منع البيع بالتوكيلات نهائياً! البيع عبر مخلصة يتم بعقد بيع نهائي ومسجل من المالك الأصلي للمشتري الجديد في الشهر العقاري فور فك الحظر.")
    ]
    for m_t, m_d in mines:
        add_p(m_t, bold=True, color=(220, 38, 38), size=11)
        for line in m_d.split("\n"):
            add_p(line, bold=False, color=(51, 65, 85), size=10.5)

    # -------------------------------------------------------------
    # SECTION 4: ADVANCED BUSINESS TERMS
    # -------------------------------------------------------------
    add_h("المحور الرابع: قاموس المصطلحات البنكية والقانونية المتقدمة:", level=2, color=(11, 45, 74))
    adv_terms = [
        ("• حوالة الحق وحوالة الدين (Debt Assignment & Subrogation):", "انتقال الحق المالي أو المديونية من طرف لآخر باتفاق الأطراف والحلول القانوني محل المدين الأصلي."),
        ("• الديون غير المنتظمة (NPLs - Non-Performing Loans):", "قروض السيارات المتأخر سدادها لأكثر من 90 يوماً وتضغط على ميزانية البنك، ومخلصة هي الحل لتنظيفها."),
        ("• خصم السداد المعجل (Early Payoff Haircut / Settlement Discount):", "الخصم الذي يمنحه البنك من الفوائد المستقبلية عند سداد القرض كاش دفعة واحدة."),
        ("• الرهن الحيازي والضمانة التبعية (Hypothecation & Collateral):", "قيد حظر البيع المسجل بالمرور كضمانة عينية للبنك."),
        ("• مكافحة غسل الأموال واعرف عميلك (AML / KYC):", "إجراءات التحقق من هوية العملاء ومصادر أموالهم.")
    ]
    for at_t, at_d in adv_terms:
        add_p(f"{at_t} {at_d}", bold=False, color=(15, 23, 42), size=10.5)

    # -------------------------------------------------------------
    # SECTION 5: PRACTICAL ROADMAP FROM TOMORROW
    # -------------------------------------------------------------
    add_h("المحور الخامس: خارطة الطريق العملية من الغد (Roadmap):", level=2, color=(11, 45, 74))
    steps = [
        ("الخطوة 1: مع الحاضنة", "طلب تأسيس شركة ذات مسؤولية محدودة (LLC) لشريكين (محمود وأخته) بنشاط وساطة تجارية وإلكترونية وإدارة منصات."),
        ("الخطوة 2: تنفيذ أول 3 عمليات Pilot على أرض الواقع", "البحث عن 3 سيارات متعثرة في محيطك وتنفيذ تسويتها بنظام الشيك المصرفي المباشر لصالح البنك وتوثيق التجربة كاملة."),
        ("الخطوة 3: التوجه لشركات التمويل (Contact, Drive, Valu)", "مقابلة مسؤولي قطاع التسويات بالشركات وتقديم سابقة أعمال الـ Pilot الناجحة لتوقيع بروتوكولات تعاون رسمية."),
        ("الخطوة 4: الأتمتة الكاملة", "تشغيل بوابات الدفع الإلكتروني وربط طلبات التسوية أوتوماتيكياً عبر المنصة mokalasa.online.")
    ]
    for st_t, st_d in steps:
        add_p(f"◄ {st_t}:", bold=True, color=(16, 185, 129), size=11)
        add_p(f"  {st_d}", bold=False, color=(51, 65, 85), size=10.5)

    # Save
    out_path = r"C:\Users\tamer.salah\Desktop\Mokhalasa_Real_World_Execution_Playbook.docx"
    doc.save(out_path)
    print(f"Playbook Word doc created: {out_path}")

if __name__ == "__main__":
    build_playbook()
