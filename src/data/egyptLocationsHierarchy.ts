export const GOVERNORATES_LIST = Object.keys(EGYPT_LOCATIONS_HIERARCHY);

export function getDistrictsForGovernorate(governorate: string): string[] {
  const govData = EGYPT_LOCATIONS_HIERARCHY[governorate];
  if (!govData) return [];
  return Object.keys(govData);
}

export function getSubAreasForDistrict(governorate: string, district: string): string[] {
  const govData = EGYPT_LOCATIONS_HIERARCHY[governorate];
  if (!govData) return [];
  return govData[district] || [];
}

export function formatFullEgyptianAddress(parts: {
  governorate?: string;
  district?: string;
  subArea?: string;
  streetDetails?: string;
}): string {
  return [parts.governorate, parts.district, parts.subArea, parts.streetDetails]
    .map((p) => (p || '').trim())
    .filter(Boolean)
    .join(' - ');
}
